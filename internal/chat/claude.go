package chat

// Claude Code's transcript (~/.claude/projects/<project>/<session>.jsonl),
// one record per line, to messages.
//
// Ported from Orca's transcript-line-decoders-claude.ts,
// transcript-record-blocks.ts, transcript-turn-lifecycle.ts,
// transcript-turn-markers.ts and shared/harness-injected-user-turns.ts,
// claude-pasted-content.ts (MIT, Copyright (c) 2026 Lovecast Inc.; see
// NOTICE): which records are shown, which are the harness's
// own machinery, where a turn starts and ends, the edit hunks a result
// carries. Unlike Orca, a command the user ran (/compact, !ls) and its
// output are shown as such rather than hidden, and Claude's "[Request
// interrupted by user for tool use]" counts as an interruption as well.

import (
	"encoding/json"
	"regexp"
	"strings"
)

type claudeDecoder struct {
	// The prompt that started the current turn.
	turn string
	// Tool names and subagents by call id, for the results.
	names map[string]string
	subs  map[string]*Subagent
	last  Turn
	// Reading a subagent's own file (<session>/subagents/agent-<id>.jsonl),
	// where every line is the sidechain.
	sidechain bool
}

// Stop reasons that end a turn (not the tool_use that goes on with one).
var claudeTerminalStops = map[string]bool{"end_turn": true, "max_tokens": true, "stop_sequence": true, "refusal": true}

// Tags the harness puts at the head of a user record that the user did not
// type: only those seen from Claude Code and its forks, never any tag.
var harnessTags = map[string]bool{
	"agent-message": true, "bash-input": true, "bash-stderr": true, "bash-stdout": true,
	"command-args": true, "command-message": true, "command-name": true,
	"cross-session-message": true, "fork-boilerplate": true, "local-command-caveat": true,
	"local-command-stderr": true, "local-command-stdout": true, "mcp-polling-update": true,
	"mcp-resource-update": true, "system-reminder": true, "task-notification": true,
	"teammate-message": true, "user-memory-input": true, "user-prompt-submit-hook": true,
}

var harnessPrefixes = []string{
	"<channel source=",
	"[request interrupted",
	"a message arrived from ",
	"another claude session sent a message",
	"no response requested.",
	"caveat: the messages below were generated by the user while running local commands",
	"this session is being continued from a previous conversation",
}

var leadingTag = regexp.MustCompile(`^<([a-z][a-z0-9-]*)(?:[\s>]|$)`)

// harnessText says whether a user record's text is the harness's own.
func harnessText(text string) bool {
	head := strings.TrimLeft(text, " \t\r\n")
	if len(head) > 256 {
		head = head[:256]
	}
	head = strings.ToLower(head)
	if m := leadingTag.FindStringSubmatch(head); m != nil && harnessTags[m[1]] {
		return true
	}
	for _, p := range harnessPrefixes {
		if strings.HasPrefix(head, p) {
			return true
		}
	}
	return false
}

func tagBody(s, tag string) (string, bool) {
	open, close := "<"+tag+">", "</"+tag+">"
	i := strings.Index(s, open)
	if i < 0 {
		return "", false
	}
	rest := s[i+len(open):]
	j := strings.Index(rest, close)
	if j < 0 {
		return rest, true
	}
	return rest[:j], true
}

var ansi = regexp.MustCompile("\x1b\\[[0-9;?]*[ -/]*[@-~]|\x1b\\][^\x07\x1b]*(?:\x07|\x1b\\\\)|\x1b[@-Z\\\\-_]")

// plain is s without terminal escapes and control characters.
func plain(s string) string {
	s = ansi.ReplaceAllString(s, "")
	return strings.Map(func(r rune) rune {
		if r < 0x20 && r != '\n' && r != '\t' || r == 0x7f {
			return -1
		}
		return r
	}, s)
}

var pastedOpen = regexp.MustCompile(`^<pasted_content(?: id="([^"<>\r\n]{1,64})")?>\r?\n`)

// unwrapPasted takes the text out of Claude's <pasted_content> wrapper when
// it wraps the whole of it.
func unwrapPasted(text string) string {
	t := strings.TrimSpace(text)
	m := pastedOpen.FindStringSubmatchIndex(t)
	if m == nil {
		return text
	}
	id := ""
	if m[2] >= 0 {
		id = t[m[2]:m[3]]
	}
	closeTag := "</pasted_content>"
	if id != "" {
		closeTag = `</pasted_content id="` + id + `">`
	}
	if !strings.HasSuffix(t, closeTag) {
		return text
	}
	body := t[m[1] : len(t)-len(closeTag)]
	ambiguous := strings.Contains(body, "<pasted_content") || strings.Contains(body, "</pasted_content")
	if id != "" {
		ambiguous = strings.Contains(body, closeTag) || strings.Contains(body, `<pasted_content id="`+id+`">`)
	}
	if !strings.HasSuffix(body, "\n") || ambiguous {
		return text
	}
	return strings.TrimSuffix(strings.TrimSuffix(body, "\n"), "\r")
}

func (d *claudeDecoder) startsTurn(line []byte) bool {
	_, t := (&claudeDecoder{names: map[string]string{}}).decode(line, 0)
	return t != nil && t.State == TurnWorking
}

// setTurn reports t when it says something new.
func (d *claudeDecoder) setTurn(t Turn) *Turn {
	if t.ID == d.last.ID && t.State == d.last.State && (t.DurationMs == 0 || d.last.DurationMs != 0) {
		return nil
	}
	d.last = t
	return &t
}

func (d *claudeDecoder) remember(callID, name string, sub *Subagent) {
	if callID == "" {
		return
	}
	if len(d.names) > 1024 {
		clear(d.names)
		clear(d.subs)
	}
	d.names[callID] = name
	if sub != nil {
		if d.subs == nil {
			d.subs = map[string]*Subagent{}
		}
		d.subs[callID] = sub
	}
}

func (d *claudeDecoder) decode(line []byte, off int64) ([]Message, *Turn) {
	var r map[string]any
	if json.Unmarshal(line, &r) != nil {
		return nil, nil
	}
	typ := str(r["type"])
	ts := timestamp(r["timestamp"])
	id := str(r["uuid"])
	if id == "" {
		id = offsetID(off)
	}
	msg := func(role string, blocks ...Block) Message {
		return Message{ID: id, Role: role, Blocks: blocks, Turn: d.turn, TS: ts, Agent: "claude", ParentID: str(r["parentUuid"]), Offset: off}
	}
	if r["isSidechain"] == true && !d.sidechain {
		// A subagent's own conversation, in the main file in older versions:
		// its Agent call and result are what the main conversation shows.
		return nil, nil
	}
	switch typ {
	case "system":
		switch str(r["subtype"]) {
		case "turn_duration":
			if d.turn == "" {
				return nil, nil
			}
			return nil, d.setTurn(Turn{ID: d.turn, State: TurnCompleted, At: ts, DurationMs: num(r["durationMs"])})
		case "compact_boundary":
			return []Message{msg(RoleSystem, Block{Type: BlockCompacted})}, nil
		case "local_command":
			if b, ok := commandOutput(str(r["content"])); ok {
				return []Message{msg(RoleSystem, b)}, nil
			}
		}
		return nil, nil
	case "user", "assistant":
	default:
		return nil, nil
	}
	message, _ := r["message"].(map[string]any)
	content := message["content"]

	if typ == "user" {
		text := userText(content)
		if str(r["interruptedMessageId"]) != "" || strings.HasPrefix(strings.ToLower(strings.TrimSpace(text)), "[request interrupted") {
			var t *Turn
			if d.turn != "" {
				t = d.setTurn(Turn{ID: d.turn, State: TurnInterrupted, At: ts})
			}
			return []Message{msg(RoleSystem, Block{Type: BlockInterrupted})}, t
		}
	}

	blocks, sub := d.blocks(content)
	if typ == "assistant" {
		if len(blocks) == 0 {
			return nil, d.assistantTurn(message, ts)
		}
		m := msg(RoleAssistant, blocks...)
		m.Subagent = sub
		m.Error = r["isApiErrorMessage"] == true
		return []Message{m}, d.assistantTurn(message, ts)
	}

	// A user record.
	hasResult := false
	for _, b := range blocks {
		if b.Type == BlockToolResult {
			hasResult = true
		}
	}
	injected := r["isMeta"] == true || r["isSynthetic"] == true || r["isCompactSummary"] == true
	if injected {
		// Tool results are real output even in a record the harness made.
		kept := blocks[:0]
		for _, b := range blocks {
			if b.Type == BlockToolResult {
				kept = append(kept, b)
			}
		}
		blocks = kept
	}
	if len(blocks) == 0 {
		return nil, nil
	}
	if hasResult {
		blocks = d.results(r, blocks)
		role := RoleTool
		for _, b := range blocks {
			if b.Type != BlockToolResult && b.Type != BlockDiff {
				role = RoleUser
			}
		}
		m := msg(role, blocks...)
		for _, b := range blocks {
			if s := d.subs[b.CallID]; s != nil {
				cp := *s
				if res, ok := r["toolUseResult"].(map[string]any); ok {
					cp.ID = str(res["agentId"])
				}
				m.Subagent = &cp
			}
		}
		return []Message{m}, nil
	}

	text := userText(content)
	// A command the user ran: /compact, a custom command, !ls.
	if name, ok := tagBody(text, "command-name"); ok && harnessText(text) {
		args, _ := tagBody(text, "command-args")
		d.turn = id
		m := msg(RoleSystem, Block{Type: BlockCommand, Name: strings.TrimSpace(name), Text: strings.TrimSpace(args)})
		m.Turn = id
		return []Message{m}, nil
	}
	if cmd, ok := tagBody(text, "bash-input"); ok && harnessText(text) {
		d.turn = id
		m := msg(RoleSystem, Block{Type: BlockCommand, Name: "!", Text: strings.TrimSpace(cmd)})
		m.Turn = id
		return []Message{m}, nil
	}
	if b, ok := commandOutput(text); ok && harnessText(text) {
		return []Message{msg(RoleSystem, b)}, nil
	}
	if harnessText(text) {
		return nil, nil
	}
	for i := range blocks {
		if blocks[i].Type == BlockText {
			blocks[i].Text = unwrapPasted(blocks[i].Text)
		}
	}
	d.turn = id
	m := msg(RoleUser, blocks...)
	m.Turn = id
	return []Message{m}, d.setTurn(Turn{ID: id, State: TurnWorking, At: ts})
}

// assistantTurn: a reply that ends the generation completes the turn; one
// that goes on (a tool call) means it is running, whatever started it (a
// prompt, a command that expanded into one, a background agent's result).
func (d *claudeDecoder) assistantTurn(message map[string]any, ts int64) *Turn {
	if d.turn == "" {
		return nil
	}
	stop, hasStop := message["stop_reason"].(string)
	content, _ := message["content"].([]any)
	renderable, toolUse := false, false
	if s, ok := message["content"].(string); ok && strings.TrimSpace(s) != "" {
		renderable = true
	}
	for _, c := range content {
		b, _ := c.(map[string]any)
		switch str(b["type"]) {
		case "text":
			renderable = renderable || strings.TrimSpace(str(b["text"])) != ""
		case "thinking", "redacted_thinking":
			renderable = true
		case "tool_use", "server_tool_use":
			toolUse = true
		}
	}
	if claudeTerminalStops[stop] || (!hasStop && renderable && !toolUse) {
		return d.setTurn(Turn{ID: d.turn, State: TurnCompleted, At: ts})
	}
	if d.last.ID != d.turn || d.last.State != TurnWorking {
		return d.setTurn(Turn{ID: d.turn, State: TurnWorking, At: ts})
	}
	return nil
}

// commandOutput is a local command's or a shell command's output.
func commandOutput(text string) (Block, bool) {
	var parts []string
	isErr := false
	for _, tag := range []string{"local-command-stdout", "bash-stdout", "local-command-stderr", "bash-stderr"} {
		if body, ok := tagBody(text, tag); ok {
			if body = strings.TrimSpace(plain(body)); body != "" {
				parts = append(parts, body)
				if strings.HasSuffix(tag, "stderr") {
					isErr = true
				}
			}
		}
	}
	if len(parts) == 0 {
		return Block{}, false
	}
	return Block{Type: BlockCommandOutput, Text: strings.Join(parts, "\n"), IsError: isErr}, true
}

// userText is the text of a user record's content.
func userText(content any) string {
	if s, ok := content.(string); ok {
		return s
	}
	var parts []string
	list, _ := content.([]any)
	for _, c := range list {
		if s, ok := c.(string); ok {
			parts = append(parts, s)
			continue
		}
		b, _ := c.(map[string]any)
		if str(b["type"]) == "text" {
			parts = append(parts, str(b["text"]))
		}
	}
	return strings.Join(parts, "")
}

// blocks maps one record's content; sub is the subagent an Agent call in it
// starts.
func (d *claudeDecoder) blocks(content any) (out []Block, sub *Subagent) {
	if s, ok := content.(string); ok {
		if strings.TrimSpace(s) != "" {
			out = append(out, Block{Type: BlockText, Text: s})
		}
		return out, nil
	}
	list, _ := content.([]any)
	for _, c := range list {
		if s, ok := c.(string); ok {
			if strings.TrimSpace(s) != "" {
				out = append(out, Block{Type: BlockText, Text: s})
			}
			continue
		}
		b, _ := c.(map[string]any)
		switch str(b["type"]) {
		case "text":
			if t := str(b["text"]); t != "" {
				out = append(out, Block{Type: BlockText, Text: t})
			}
		case "thinking":
			// Recent versions keep only a signature: nothing to show.
			if t := str(b["thinking"]); strings.TrimSpace(t) != "" {
				out = append(out, Block{Type: BlockReasoning, Text: t})
			}
		case "tool_use", "server_tool_use":
			name := str(b["name"])
			if name == "" {
				name = "tool"
			}
			callID := str(b["id"])
			var s *Subagent
			if in, ok := b["input"].(map[string]any); ok && (name == "Agent" || name == "Task") {
				s = &Subagent{Type: str(in["subagent_type"]), Description: oneLine(str(in["description"]))}
				sub = s
			}
			d.remember(callID, name, s)
			out = append(out, Block{Type: BlockToolCall, Name: name, CallID: callID, Summary: summarize(b["input"]), Input: b["input"]})
		case "tool_result", "web_search_tool_result":
			callID := str(b["tool_use_id"])
			out = append(out, Block{Type: BlockToolResult, CallID: callID, Name: d.names[callID], Output: resultOutput(b["content"]), IsError: b["is_error"] == true})
		case "image":
			// Never the bytes.
			out = append(out, Block{Type: BlockImage})
		}
	}
	return out, sub
}

// results adds the edit's hunks after its result.
func (d *claudeDecoder) results(r map[string]any, blocks []Block) []Block {
	res, _ := r["toolUseResult"].(map[string]any)
	raw, _ := res["structuredPatch"].([]any)
	if len(raw) == 0 {
		return blocks
	}
	diff := Block{Type: BlockDiff, Path: str(res["filePath"])}
	for _, e := range raw {
		if len(diff.Hunks) >= maxHunks {
			break
		}
		h, _ := e.(map[string]any)
		lines, ok := h["lines"].([]any)
		os, ok1 := h["oldStart"].(float64)
		ns, ok2 := h["newStart"].(float64)
		if !ok || !ok1 || !ok2 {
			continue
		}
		hunk := Hunk{OldStart: int(os), NewStart: int(ns), OldLines: int(num(h["oldLines"])), NewLines: int(num(h["newLines"]))}
		for _, l := range lines {
			if len(hunk.Lines) >= maxHunkLines {
				break
			}
			if s, ok := l.(string); ok {
				s, _, _ = clipText(s, maxDiffLine)
				hunk.Lines = append(hunk.Lines, s)
			}
		}
		diff.Hunks = append(diff.Hunks, hunk)
	}
	if len(diff.Hunks) == 0 {
		return blocks
	}
	out := make([]Block, 0, len(blocks)+1)
	added := false
	for _, b := range blocks {
		out = append(out, b)
		if !added && b.Type == BlockToolResult {
			out = append(out, diff)
			added = true
		}
	}
	return out
}

// resultOutput is a tool result's content as one string.
func resultOutput(v any) string {
	switch t := v.(type) {
	case string:
		return t
	case nil:
		return ""
	case []any:
		var parts []string
		for _, it := range t {
			if s, ok := it.(string); ok {
				parts = append(parts, s)
				continue
			}
			m, _ := it.(map[string]any)
			if s := str(m["text"]); s != "" {
				parts = append(parts, s)
			} else if s := str(m["content"]); s != "" {
				parts = append(parts, s)
			}
		}
		return strings.Join(parts, "\n")
	case map[string]any:
		if s := str(t["text"]); s != "" {
			return s
		}
		if s := str(t["content"]); s != "" {
			return s
		}
	}
	b, _ := json.Marshal(v)
	return string(b)
}
